export function getCitiesForState(state: string) {
  return indianLocations.find((item) => item.state === state)?.cities ?? [];
}

export function formatLocation(city: string, state: string) {
  const cleanCity = city.replace(/,/g, " ").replace(/\s+/g, " ").trim();
  const cleanState = state.trim();
  return cleanCity && cleanState ? `${cleanCity}, ${cleanState}` : "";
}

export function parseLocation(value: string | null | undefined) {
  const [city = "", state = ""] = (value ?? "").split(",").map((part) => part.trim());
  const inferredState = state || indianLocations.find((item) => item.cities.includes(city))?.state || "";
  return {
    city,
    state: inferredState,
  };
}
